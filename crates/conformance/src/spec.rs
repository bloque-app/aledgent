//! The spec catalogue (`F-015` §1, T-015-01).
//!
//! [`parse_spec`] reads `SPEC.md`: every `INV-*` of §9 with the layers it
//! names, every `ERR-*` of §10 with its condition, and every `AC-*` of the
//! stories §15 puts in V0. [`Catalogue::render`] writes it as
//! `spec/catalogue.toml`, which is checked in. `cargo xtask spec-ids --check`
//! regenerates it and fails on any difference, so a spec change cannot land
//! without the suite noticing.
//!
//! `spec/floor.toml` is hand-written from `REQ-AR-6`; see [`Floor`].

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use serde::{Deserialize, Serialize};

use crate::case::Layer;

/// The checked-in catalogue, compiled into the suite.
pub const CATALOGUE_TOML: &str = include_str!("../spec/catalogue.toml");

/// The checked-in floor of `REQ-AR-6`, compiled into the suite.
pub const FLOOR_TOML: &str = include_str!("../spec/floor.toml");

/// `SPEC.md` as it is in this checkout, compiled into the suite so the
/// catalogue check needs no file access.
pub const SPEC_MD: &str = include_str!("../../../SPEC.md");

/// Every identifier the suite must cover, generated from `SPEC.md`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Catalogue {
    /// The spec version the catalogue was generated from.
    pub spec_version: String,
    /// SPEC §9, in order.
    #[serde(rename = "invariant")]
    pub invariants: Vec<InvariantEntry>,
    /// SPEC §10, in order.
    #[serde(rename = "error")]
    pub errors: Vec<ErrorEntry>,
    /// The acceptance criteria of the V0 stories (§15 "Release scope").
    #[serde(rename = "acceptance")]
    pub acceptance: Vec<AcceptanceEntry>,
}

/// One row of SPEC §9.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct InvariantEntry {
    /// `INV-n`.
    pub id: String,
    /// The layers the "Enforced by" column names (`REQ-AR-4`): the target.
    pub layers: Vec<Layer>,
    /// The layers the "V0" column names: where the first release enforces it (`REQ-AR-6`,
    /// amendment 0006 item 2).
    pub v0: Vec<Layer>,
    /// The invariant, verbatim.
    pub text: String,
}

/// One row of SPEC §10.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ErrorEntry {
    /// `ERR-Name`.
    pub id: String,
    /// The published condition, verbatim (`REQ-ER-1`).
    pub condition: String,
}

/// One acceptance criterion of a V0 story.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AcceptanceEntry {
    /// `AC-X1.n`.
    pub id: String,
    /// The story it belongs to, `US-X1`.
    pub story: String,
    /// The epic letter, `X`.
    pub epic: String,
    /// The criterion, verbatim, with its line breaks joined.
    pub text: String,
}

impl Catalogue {
    /// The checked-in catalogue. Panics if the file does not parse, which the
    /// catalogue check reports first.
    pub fn checked_in() -> Catalogue {
        Catalogue::from_toml(CATALOGUE_TOML).expect("spec/catalogue.toml parses")
    }

    /// Parse a rendered catalogue.
    pub fn from_toml(text: &str) -> Result<Catalogue, String> {
        toml::from_str(text).map_err(|e| e.to_string())
    }

    /// The invariant with this id.
    pub fn invariant(&self, id: &str) -> Option<&InvariantEntry> {
        self.invariants.iter().find(|i| i.id == id)
    }

    /// The error with this id.
    pub fn error(&self, id: &str) -> Option<&ErrorEntry> {
        self.errors.iter().find(|e| e.id == id)
    }

    /// The acceptance criterion with this id.
    pub fn acceptance(&self, id: &str) -> Option<&AcceptanceEntry> {
        self.acceptance.iter().find(|a| a.id == id)
    }

    /// Whether any family of the catalogue holds `id`.
    pub fn contains(&self, id: &str) -> bool {
        self.invariant(id).is_some() || self.error(id).is_some() || self.acceptance(id).is_some()
    }

    /// Every id, in catalogue order: invariants, errors, acceptance criteria.
    pub fn ids(&self) -> impl Iterator<Item = &str> {
        self.invariants
            .iter()
            .map(|i| i.id.as_str())
            .chain(self.errors.iter().map(|e| e.id.as_str()))
            .chain(self.acceptance.iter().map(|a| a.id.as_str()))
    }

    /// The catalogue as `spec/catalogue.toml`: deterministic, one entry per
    /// table, in SPEC order.
    pub fn render(&self) -> String {
        let mut out = String::new();
        out.push_str(
            "# Generated by `cargo xtask spec-ids` from SPEC.md. Do not edit by hand:\n\
             # CI regenerates this file and fails on any difference (F-015 §1).\n",
        );
        let _ = writeln!(
            out,
            "# {} invariants (§9), {} errors (§10), {} V0 acceptance criteria (§6, §15).\n",
            self.invariants.len(),
            self.errors.len(),
            self.acceptance.len()
        );
        let _ = writeln!(out, "spec_version = {}", quote(&self.spec_version));
        for i in &self.invariants {
            let layers: Vec<String> = i.layers.iter().map(|l| quote(l.as_str())).collect();
            let v0: Vec<String> = i.v0.iter().map(|l| quote(l.as_str())).collect();
            let _ = write!(
                out,
                "\n[[invariant]]\nid = {}\nlayers = [{}]\nv0 = [{}]\ntext = {}\n",
                quote(&i.id),
                layers.join(", "),
                v0.join(", "),
                quote(&i.text)
            );
        }
        for e in &self.errors {
            let _ = write!(
                out,
                "\n[[error]]\nid = {}\ncondition = {}\n",
                quote(&e.id),
                quote(&e.condition)
            );
        }
        for a in &self.acceptance {
            let _ = write!(
                out,
                "\n[[acceptance]]\nid = {}\nstory = {}\nepic = {}\ntext = {}\n",
                quote(&a.id),
                quote(&a.story),
                quote(&a.epic),
                quote(&a.text)
            );
        }
        out
    }
}

/// A TOML basic string.
fn quote(s: &str) -> String {
    let mut q = String::with_capacity(s.len() + 2);
    q.push('"');
    for c in s.chars() {
        match c {
            '"' => q.push_str("\\\""),
            '\\' => q.push_str("\\\\"),
            '\n' => q.push_str("\\n"),
            '\t' => q.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(q, "\\u{:04X}", c as u32);
            }
            c => q.push(c),
        }
    }
    q.push('"');
    q
}

/// The lines of `text` from the heading that starts with `from` up to, not
/// including, the next heading that starts with `to`.
fn section<'a>(text: &'a str, from: &str, to: &str) -> Result<Vec<&'a str>, String> {
    let mut lines = text.lines().skip_while(|l| !l.starts_with(from));
    if lines.next().is_none() {
        return Err(format!("SPEC.md has no heading `{from}`"));
    }
    Ok(lines.take_while(|l| !l.starts_with(to)).collect())
}

/// The cells of a Markdown table row, trimmed.
fn cells(line: &str) -> Vec<&str> {
    line.trim()
        .trim_start_matches('|')
        .trim_end_matches('|')
        .split('|')
        .map(str::trim)
        .collect()
}

/// The text between the first pair of backticks.
fn backticked(s: &str) -> Option<&str> {
    let start = s.find('`')? + 1;
    let len = s[start..].find('`')?;
    Some(&s[start..start + len])
}

/// Parse "Kernel + store", "Store (continuously checked)", "Store + build
/// gate" and the like.
fn parse_layers(cell: &str) -> Result<Vec<Layer>, String> {
    let without_note = match cell.find('(') {
        Some(i) => &cell[..i],
        None => cell,
    };
    without_note
        .split('+')
        .map(|w| {
            let word = w.trim().to_lowercase().replace(' ', "-");
            Layer::parse(&word).ok_or_else(|| format!("unknown layer `{}` in `{cell}`", w.trim()))
        })
        .collect()
}

/// Expand the story ids in a release-scope cell: "`US-A1`, `US-A4`–`US-A8`".
fn stories_in(cell: &str) -> Result<Vec<(String, u32)>, String> {
    let mut out = Vec::new();
    let mut rest = cell;
    let mut range_from: Option<(String, u32)> = None;
    while let Some(start) = rest.find('`') {
        let between = &rest[..start];
        let after = &rest[start + 1..];
        let Some(len) = after.find('`') else { break };
        let token = &after[..len];
        rest = &after[len + 1..];
        let Some(story) = token.strip_prefix("US-") else {
            continue;
        };
        let split = story
            .find(|c: char| c.is_ascii_digit())
            .ok_or_else(|| format!("bad story id `{token}`"))?;
        let epic = story[..split].to_string();
        let n: u32 = story[split..]
            .parse()
            .map_err(|_| format!("bad story id `{token}`"))?;
        if between.trim() == "–" {
            let (from_epic, from_n) = range_from
                .take()
                .ok_or_else(|| format!("range with no start before `{token}`"))?;
            if from_epic != epic || from_n > n {
                return Err(format!("bad range ending `{token}`"));
            }
            out.extend((from_n + 1..=n).map(|k| (epic.clone(), k)));
        } else {
            out.push((epic.clone(), n));
        }
        range_from = Some((epic, n));
    }
    Ok(out)
}

/// Read the catalogue out of `SPEC.md`.
pub fn parse_spec(text: &str) -> Result<Catalogue, String> {
    let spec_version = text
        .lines()
        .find_map(|l| l.strip_prefix("spec_version:"))
        .map(|v| v.trim().to_string())
        .ok_or("SPEC.md has no `spec_version:` in its front matter")?;

    let mut invariants = Vec::new();
    for line in section(text, "## 9.", "## 10.")? {
        if !line.starts_with("| `INV-") {
            continue;
        }
        let c = cells(line);
        if c.len() != 4 {
            return Err(format!(
                "§9 row does not have four cells (id, invariant, target, V0): {line}"
            ));
        }
        let id = backticked(c[0]).ok_or_else(|| format!("§9 row without id: {line}"))?;
        invariants.push(InvariantEntry {
            id: id.to_string(),
            layers: parse_layers(c[2])?,
            v0: parse_layers(c[3])?,
            text: c[1].to_string(),
        });
    }

    let mut errors = Vec::new();
    for line in section(text, "## 10.", "## 11.")? {
        if !line.starts_with("| `ERR-") {
            continue;
        }
        let c = cells(line);
        if c.len() != 2 {
            return Err(format!("§10 row does not have two cells: {line}"));
        }
        let id = backticked(c[0]).ok_or_else(|| format!("§10 row without id: {line}"))?;
        errors.push(ErrorEntry {
            id: id.to_string(),
            condition: c[1].to_string(),
        });
    }

    // V0 stories, from the release-scope table of §15.
    let mut v0: BTreeSet<String> = BTreeSet::new();
    let scope = section(text, "### Release scope", "## ")?;
    for line in scope.iter().filter(|l| l.starts_with('|')) {
        let c = cells(line);
        if c.len() != 3 || !c[0].contains('—') {
            continue;
        }
        for (epic, n) in stories_in(c[1])? {
            v0.insert(format!("US-{epic}{n}"));
        }
    }
    if v0.is_empty() {
        return Err("§15 release scope names no V0 story".into());
    }

    // Acceptance criteria of those stories, from §6.
    let mut acceptance = Vec::new();
    let mut seen_stories = BTreeSet::new();
    let stories = section(text, "## 6.", "## 7.")?;
    let mut story: Option<String> = None;
    let mut i = 0;
    while i < stories.len() {
        let line = stories[i];
        if let Some(rest) = line.strip_prefix("**`US-") {
            let id = rest.split('`').next().unwrap_or_default();
            story = Some(format!("US-{id}"));
            seen_stories.insert(format!("US-{id}"));
        } else if line.starts_with("- `AC-") {
            let id = backticked(line)
                .ok_or_else(|| format!("AC line without id: {line}"))?
                .to_string();
            let mut body = line
                .split_once(char::is_whitespace)
                .map(|(_, r)| r)
                .unwrap_or_default()
                .trim_start()
                .strip_prefix(&format!("`{id}`"))
                .unwrap_or_default()
                .trim()
                .to_string();
            while i + 1 < stories.len() && stories[i + 1].starts_with("  ") {
                i += 1;
                body.push(' ');
                body.push_str(stories[i].trim());
            }
            let owner = story
                .clone()
                .ok_or_else(|| format!("{id} appears before any story"))?;
            if v0.contains(&owner) {
                let epic = owner
                    .trim_start_matches("US-")
                    .trim_end_matches(|c: char| c.is_ascii_digit())
                    .to_string();
                acceptance.push(AcceptanceEntry {
                    id,
                    story: owner,
                    epic,
                    text: body,
                });
            }
        }
        i += 1;
    }
    if let Some(missing) = v0.iter().find(|s| !seen_stories.contains(*s)) {
        return Err(format!("§15 puts {missing} in V0 but §6 has no such story"));
    }

    let catalogue = Catalogue {
        spec_version,
        invariants,
        errors,
        acceptance,
    };
    check_unique(&catalogue)?;
    Ok(catalogue)
}

fn check_unique(c: &Catalogue) -> Result<(), String> {
    let mut seen = BTreeSet::new();
    for id in c.ids() {
        if !seen.insert(id) {
            return Err(format!("{id} appears twice in SPEC.md"));
        }
    }
    if c.invariants.is_empty() || c.errors.is_empty() || c.acceptance.is_empty() {
        return Err("SPEC.md gave an empty family".into());
    }
    Ok(())
}

/// Compare the catalogue `SPEC.md` gives with the checked-in one. `Err`
/// holds the ids added, removed or changed, for the CI log.
pub fn check_current(spec: &str, checked_in: &str) -> Result<(), String> {
    let fresh = parse_spec(spec)?;
    if fresh.render() == checked_in {
        return Ok(());
    }
    let old = Catalogue::from_toml(checked_in).map_err(|e| {
        format!(
            "spec/catalogue.toml does not parse ({e}); regenerate it with `cargo xtask spec-ids`"
        )
    })?;
    let mut diff = Vec::new();
    let entries = |c: &Catalogue| -> BTreeMap<String, String> {
        let mut m = BTreeMap::new();
        for i in &c.invariants {
            m.insert(
                i.id.clone(),
                format!("{:?} {:?} {}", i.layers, i.v0, i.text),
            );
        }
        for e in &c.errors {
            m.insert(e.id.clone(), e.condition.clone());
        }
        for a in &c.acceptance {
            m.insert(a.id.clone(), a.text.clone());
        }
        m
    };
    let (a, b) = (entries(&old), entries(&fresh));
    for (id, v) in &b {
        match a.get(id) {
            None => diff.push(format!("+ {id}")),
            Some(w) if w != v => diff.push(format!("~ {id}")),
            _ => {}
        }
    }
    diff.extend(
        a.keys()
            .filter(|id| !b.contains_key(*id))
            .map(|id| format!("- {id}")),
    );
    if old.spec_version != fresh.spec_version {
        diff.push(format!(
            "~ spec_version {} -> {}",
            old.spec_version, fresh.spec_version
        ));
    }
    if diff.is_empty() {
        diff.push("formatting only".into());
    }
    Err(format!(
        "spec/catalogue.toml is not current with SPEC.md; run `cargo xtask spec-ids`:\n  {}",
        diff.join("\n  ")
    ))
}

/// The floor of `REQ-AR-6`, hand-written in `spec/floor.toml`.
#[derive(Clone, Debug, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Floor {
    /// The requirement the floor transcribes.
    pub basis: String,
    /// Each line of the floor: these ids, enforced at one of these layers.
    #[serde(rename = "require")]
    pub requirements: Vec<FloorRequirement>,
    /// Invariants the first release declares at another layer than §9
    /// names, because `REQ-AR-6` says so.
    #[serde(rename = "v0_layer", default)]
    pub v0_layers: Vec<V0Layer>,
    /// How disclosures are declared.
    pub disclosures: Disclosures,
}

/// One line of `REQ-AR-6`.
#[derive(Clone, Debug, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct FloorRequirement {
    /// The invariants the line covers.
    pub ids: Vec<String>,
    /// The id must be enforced at one of these layers.
    pub layers: Vec<Layer>,
    /// The wording of the line, for the CI log.
    pub text: String,
}

/// An invariant `REQ-AR-6` declares at another layer than SPEC §9 names.
#[derive(Clone, Debug, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct V0Layer {
    /// The invariant.
    pub id: String,
    /// The layers the first release declares it at.
    pub layers: Vec<Layer>,
    /// Why, and what disagrees.
    pub note: String,
}

/// The disclosure posture (`REQ-PR-6`).
#[derive(Clone, Debug, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Disclosures {
    /// `signed-assertion` until `DEF-3`.
    pub mode: String,
    /// `REQ-PR-6`.
    pub basis: String,
}

impl Floor {
    /// The checked-in floor.
    pub fn checked_in() -> Floor {
        Floor::from_toml(FLOOR_TOML).expect("spec/floor.toml parses")
    }

    /// Parse a floor file.
    pub fn from_toml(text: &str) -> Result<Floor, String> {
        toml::from_str(text).map_err(|e| e.to_string())
    }

    /// The layers the first release declares `id` at, if `REQ-AR-6` moves it
    /// off the layers §9 names.
    pub fn v0_layers_of(&self, id: &str) -> Option<&V0Layer> {
        self.v0_layers.iter().find(|v| v.id == id)
    }
}

